# frozen_string_literal: true

require "rails/generators"

module OrbitalUi
  module Generators
    # Sets up an app to use Orbital. It's safe to run again, for example after an upgrade.
    class InstallGenerator < Rails::Generators::Base
      THEME = File.expand_path("../../../../app/assets/stylesheets/orbital_ui/theme.css", __dir__)
      TAILWIND_MARKER = "/* --- Tailwind Integration --- */"
      TAILWIND_ENTRY = "app/assets/stylesheets/application.tailwind.css"
      TAILWIND_THEME = "app/assets/stylesheets/orbital_ui.tailwind.css"
      TAILWIND_IMPORT = %(@import "./orbital_ui.tailwind.css";\n)
      INITIALIZER = "config/initializers/orb.rb"
      NAMESPACE = "ORB.namespaces += %w[OrbitalUi]\n"
      LAYOUT = "app/views/layouts/application.html.erb"
      STYLESHEET_TAG = %(<%= stylesheet_link_tag "orbital_ui/index" %>)
      JAVASCRIPT_TAG = %(<%= javascript_include_tag "orbital_ui/index", type: "module" %>)
      DIALOG_FRAME = %(<turbo-frame id="dialogs"></turbo-frame>)

      desc "Adds Orbital's ORB namespace, layout tags and, in Tailwind apps, its Tailwind theme."

      def add_orb_namespace
        if !exist?(INITIALIZER)
          create_file INITIALIZER, NAMESPACE
        elsif read(INITIALIZER).include?("OrbitalUi")
          say_status :identical, INITIALIZER
        else
          append_to_file INITIALIZER, NAMESPACE
        end
      end

      def add_tailwind_theme
        unless exist?(TAILWIND_ENTRY)
          say_status :info, "No #{TAILWIND_ENTRY}, so no Tailwind theme is needed.", :blue
          return
        end

        create_file TAILWIND_THEME, tailwind_theme, force: true
        add_tailwind_import
      end

      def add_layout_tags
        return print_layout_tags unless exist?(LAYOUT)

        layout = read(LAYOUT)
        first_stylesheet = layout[/^[ \t]*<%= stylesheet_link_tag.*\n/]
        return print_layout_tags unless first_stylesheet

        indent = first_stylesheet[/\A[ \t]*/]
        tags = []
        tags << "#{indent}#{STYLESHEET_TAG}\n" unless layout.match?(%r{stylesheet_link_tag ["']orbital_ui/index})
        tags << "#{indent}#{JAVASCRIPT_TAG}\n" unless layout.match?(%r{javascript_include_tag ["']orbital_ui/index})

        return say_status(:identical, LAYOUT) if tags.empty?

        insert_into_file LAYOUT, tags.join, before: first_stylesheet
      end

      # Dialogs loaded from the server, such as <Button modal url="...">, render into this frame.
      def add_dialog_frame
        return unless exist?(LAYOUT)

        layout = read(LAYOUT)
        return if layout.match?(/id=["']dialogs["']|turbo_frame_tag ["']dialogs["']/) || layout.exclude?("</body>")

        indent = layout[%r{^([ \t]*)</body>}, 1].to_s
        insert_into_file LAYOUT, "#{indent}  #{DIALOG_FRAME}\n", before: "#{indent}</body>"
      end

      # :app links every file in app/assets, including the raw Tailwind sources, whose @imports fail in a browser.
      def link_built_tailwind_stylesheet
        return unless exist?(TAILWIND_ENTRY) && exist?(LAYOUT) && read(LAYOUT).match?(/stylesheet_link_tag :app\b/)

        gsub_file LAYOUT, /stylesheet_link_tag :app\b/, 'stylesheet_link_tag "application"'
        gsub_file LAYOUT, %r{^[ \t]*<%# Includes all stylesheet files in app/assets/stylesheets %>\n}, ""
      end

      private

      def add_tailwind_import
        entry = read(TAILWIND_ENTRY)
        return say_status(:identical, TAILWIND_ENTRY) if entry.include?(TAILWIND_IMPORT)

        tailwind_import = entry[/^@import\s+["']tailwindcss["'].*\n/]
        unless tailwind_import
          return say_status(:skip, "Add #{TAILWIND_IMPORT.strip} to #{TAILWIND_ENTRY}.",
            :yellow)
        end

        insert_into_file TAILWIND_ENTRY, TAILWIND_IMPORT, after: tailwind_import
      end

      def tailwind_theme
        <<~CSS
          /* Generated by bin/rails generate orbital_ui:install. Run it again after upgrading orbital_ui. */

          #{File.read(THEME).split(TAILWIND_MARKER).last.strip}
        CSS
      end

      def print_layout_tags
        say_status :skip, "Add these to your layout, before your own stylesheet:", :yellow
        say "  #{STYLESHEET_TAG}\n  #{JAVASCRIPT_TAG}"
        say "And this inside <body>, for dialogs loaded from the server:\n  #{DIALOG_FRAME}"
      end

      def exist?(path)
        File.exist?(File.join(destination_root, path))
      end

      def read(path)
        File.read(File.join(destination_root, path))
      end
    end
  end
end
