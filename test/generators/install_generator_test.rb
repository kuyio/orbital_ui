# frozen_string_literal: true

require "test_helper"
require "rails/generators/test_case"
require "generators/orbital_ui/install/install_generator"

module OrbitalUi
  class InstallGeneratorTest < Rails::Generators::TestCase
    tests Generators::InstallGenerator
    destination File.expand_path("../../tmp/install_generator_test", __dir__)
    setup :prepare_destination
    teardown { FileUtils.rm_rf(destination_root) }

    LAYOUT = <<~ERB
      <html>
        <head>
          <%# Includes all stylesheet files in app/assets/stylesheets %>
          <%= stylesheet_link_tag :app, "data-turbo-track": "reload" %>
          <%= stylesheet_link_tag "other" %>
        </head>
        <body>
          <%= yield %>
        </body>
      </html>
    ERB

    def write(path, content)
      file = File.join(destination_root, path)
      FileUtils.mkdir_p(File.dirname(file))
      File.write(file, content)
    end

    def read(path)
      File.read(File.join(destination_root, path))
    end

    def write_tailwind_app
      write("app/assets/stylesheets/application.tailwind.css",
        %(@import "tailwindcss";\n\n:root {\n  --radius: 2px;\n}\n))
      write("app/views/layouts/application.html.erb", LAYOUT)
    end

    test "creates the ORB initializer" do
      run_generator

      assert_file "config/initializers/orb.rb", "ORB.namespaces += %w[OrbitalUi]\n"
    end

    test "adds to an existing ORB initializer" do
      write("config/initializers/orb.rb", "ORB.namespaces = %w[Portal]\n")
      run_generator

      assert_file "config/initializers/orb.rb", "ORB.namespaces = %w[Portal]\nORB.namespaces += %w[OrbitalUi]\n"
    end

    test "writes the Tailwind theme from the gem's theme.css, without its colour values" do
      write_tailwind_app
      run_generator

      assert_file "app/assets/stylesheets/orbital_ui.tailwind.css" do |css|
        assert_includes css, "@custom-variant dark (&:where(.dark, .dark *));"
        assert_includes css, "--color-primary: var(--primary);"
        assert_includes css, "Generated by bin/rails generate orbital_ui:install"
        assert_no_match(/^:root/, css)
      end
    end

    test "imports the theme after tailwindcss" do
      write_tailwind_app
      run_generator

      assert_file "app/assets/stylesheets/application.tailwind.css",
        %(@import "tailwindcss";\n@import "./orbital_ui.tailwind.css";\n\n:root {\n  --radius: 2px;\n}\n)
    end

    test "adds layout tags once, before the app's first stylesheet" do
      write_tailwind_app
      run_generator

      layout = read("app/views/layouts/application.html.erb")
      lines = layout.lines.map(&:strip)

      assert_equal 1, layout.scan('stylesheet_link_tag "orbital_ui/index"').size
      assert_equal 1, layout.scan('javascript_include_tag "orbital_ui/index"').size
      first_orbital = lines.index { |line| line.include?("orbital_ui/index") }
      first_app = lines.index { |line| line.include?(%("application")) }

      assert_operator first_orbital, :<, first_app
      assert_includes layout, %(    <%= stylesheet_link_tag "orbital_ui/index" %>\n)
    end

    test "running it again changes nothing" do
      write_tailwind_app
      run_generator
      paths = %w[
        config/initializers/orb.rb
        app/assets/stylesheets/application.tailwind.css
        app/assets/stylesheets/orbital_ui.tailwind.css
        app/views/layouts/application.html.erb
      ]
      before = paths.index_with { |path| read(path) }
      run_generator

      paths.each { |path| assert_equal before[path], read(path), path }
    end

    test "refreshes the Tailwind theme when run again" do
      write_tailwind_app
      write("app/assets/stylesheets/orbital_ui.tailwind.css", "stale")
      run_generator

      assert_file "app/assets/stylesheets/orbital_ui.tailwind.css", /--color-primary/
    end

    test "adds the dialog frame inside body, once" do
      write_tailwind_app
      run_generator
      run_generator

      layout = read("app/views/layouts/application.html.erb")

      assert_equal 1, layout.scan(%(<turbo-frame id="dialogs"></turbo-frame>)).size
      assert_includes layout, %(    <turbo-frame id="dialogs"></turbo-frame>\n  </body>)
    end

    test "keeps an existing dialog frame" do
      write("app/views/layouts/application.html.erb", <<~ERB)
        <head><%= stylesheet_link_tag :app %></head>
        <body><%= turbo_frame_tag "dialogs" %></body>
      ERB
      run_generator

      assert_not_includes read("app/views/layouts/application.html.erb"), "<turbo-frame"
    end

    test "a Tailwind app links the built stylesheet instead of :app, keeping its options" do
      write_tailwind_app
      run_generator

      assert_file "app/views/layouts/application.html.erb" do |layout|
        assert_includes layout, %(<%= stylesheet_link_tag "application", "data-turbo-track": "reload" %>)
        assert_not_includes layout, ":app"
        assert_not_includes layout, "Includes all stylesheet files"
      end
    end

    test "a Sass app keeps its :app stylesheet tag" do
      write("app/assets/stylesheets/application.sass.scss", "// Entry point\n")
      write("app/views/layouts/application.html.erb", LAYOUT)
      run_generator

      assert_file "app/views/layouts/application.html.erb", /stylesheet_link_tag :app/
    end

    test "a Sass app gets the initializer and layout tags, and no Tailwind theme" do
      write("app/assets/stylesheets/application.sass.scss", "// Entry point for your Sass build\n")
      write("app/views/layouts/application.html.erb", LAYOUT)
      output = run_generator

      assert_file "config/initializers/orb.rb"
      assert_file "app/views/layouts/application.html.erb", %r{stylesheet_link_tag "orbital_ui/index"}
      assert_file "app/assets/stylesheets/application.sass.scss", "// Entry point for your Sass build\n"
      assert_no_file "app/assets/stylesheets/orbital_ui.tailwind.css"
      assert_includes output, "no Tailwind theme is needed"
      assert_no_match(/skip/, output)
    end

    test "without a layout it prints the tags to add" do
      output = run_generator

      assert_includes output, %(<%= stylesheet_link_tag "orbital_ui/index" %>)
      assert_includes output, %(<%= javascript_include_tag "orbital_ui/index", type: "module" %>)
    end

    test "explains the import when application.css does not import tailwindcss" do
      write("app/assets/stylesheets/application.tailwind.css", "body {}\n")
      output = run_generator

      assert_includes output, %(Add @import "./orbital_ui.tailwind.css";)
      assert_file "app/assets/stylesheets/application.tailwind.css", "body {}\n"
    end
  end
end
